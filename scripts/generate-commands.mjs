import ts from 'typescript-api';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

// Explicit mutation allowlist. Internal helpers and arbitrary functions are never RPC endpoints.
const modules = {
  cart: 'addToCart setCartLine removeCartLine',
  address: 'addAddress updateAddress deleteAddress setDefaultAddress',
  checkout: 'placeCheckout',
  orders: 'customerCancel customerRequestCancel customerConfirmReceived customerSwitchRemainingToCod coopConfirm coopReject coopReportReady ensureRemainingTransaction coopCannotSupply coopHandover coopReceiveReturn coopDecideCancelRequest carrierSimulate',
  payment: 'applyGatewayResult',
  account: 'updateCustomerProfile linkRefundAccount unlinkRefundAccount opsCreateAccount opsSetAccountLocked rootSetAdminGroup',
  productChanges: 'coopUpdateStock coopCreateProduct coopRequestContentChange coopSetProductHidden coopRequestExpress coopRequestCertification coopRequestPriceChange coopRequestPreorder decideProductChange',
  coopProfile: 'coopSubmitProfile qualityDecideCoopProfile qualitySetSellingRights',
  coopContact: 'coopSetPhones coopSetAddress',
  complaint: 'submitComplaint coopReplyTicket cskhUpdateTicket cskhRequestCoopReply',
  reviews: 'submitReview coopReplyReview cskhSetReviewVisibility',
  adminConfig: 'opsUpdateParam opsSaveWard opsDeleteWard opsSaveGiftBox opsDeleteGiftBox adminCreateVoucher adminSetVoucherActive',
  settlement: 'closePeriod recordPayout',
  finance: 'startRefundProcessing confirmRefundBySimBank',
  harvest: 'coopConfirmHarvest',
  orderContact: 'sendOrderMessage logCoopCall markOrderChatRead',
  coopChat: 'sendDirectMessage markThreadRead',
  coopApplication: 'submitCoopApplication resubmitCoopApplication qualityAcceptApplication qualitySetCheck qualityRequestInfo qualityDecideApplication',
  shipper: 'opsAssignShipper shipperPickUp shipperDelivered shipperFailed shipperRefused shipperRemitCod financeConfirmRemittance',
  marketplace: 'setFavorite setFollow saveVoucher unsaveVoucher',
  seasonWatch: 'setSeasonWatch',
  invoice: 'saveInvoiceDefault',
  notifications: 'markNotificationsRead',
  orderEdits: 'customerChangeAddress customerChangeDeliveryDate customerEditGift',
  orderTabs: 'reorderToCart',
  variants: 'coopAddVariant',
  demoAccess: 'rootSetDemoCode rootClearDemoCode demoGatewaySuccess',
};
const registry = {};
mkdirSync('src/store/commands', {recursive:true});
for (const [module, names] of Object.entries(modules)) {
  const source = ts.createSourceFile(module+'.ts', readFileSync(`src/domain/${module}.ts`,'utf8'), ts.ScriptTarget.Latest, true);
  let bridge = `// Generated by scripts/generate-commands.mjs.\nexport * from '../../domain/${module}';\nimport * as domain from '../../domain/${module}';\nimport { invoke } from '../commandCapture';\n`;
  for (const name of names.split(' ')) {
    const fn = source.statements.find(s=>ts.isFunctionDeclaration(s)&&s.name?.text===name);
    if (!fn) throw new Error(`Missing command ${module}.${name}`);
    registry[name] = {module, params:fn.parameters.map(p=>({name:p.name.getText(source),type:p.type?.getText(source)??(p.initializer?(p.initializer.kind===ts.SyntaxKind.TrueKeyword||p.initializer.kind===ts.SyntaxKind.FalseKeyword?'boolean':ts.isStringLiteral(p.initializer)?'string':ts.isNumericLiteral(p.initializer)?'number':'unknown'):'unknown'),optional:!!(p.questionToken||p.initializer)}))};
    bridge += `export const ${name}: typeof domain.${name} = ((...args: any[]) => invoke('${name}', domain.${name} as any, args)) as typeof domain.${name};\n`;
  }
  writeFileSync(`src/store/commands/${module}.ts`, bridge);
}
writeFileSync('server/commands.json', JSON.stringify(registry,null,2)+'\n');
